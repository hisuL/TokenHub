#!/usr/bin/env bash
set -euo pipefail

default_install_root=/opt/tokenhub-silang
common_script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
installed_root_candidate="$(cd "$common_script_dir/../.." && pwd)"
if [[ -f "$installed_root_candidate/.env" && -f "$installed_root_candidate/app/docker-compose.yml" ]]; then
  default_install_root="$installed_root_candidate"
fi
install_root="${TOKENHUB_INSTALL_ROOT:-$default_install_root}"
env_file="$install_root/.env"
compose_file="$install_root/app/docker-compose.yml"

die() {
  printf '[TokenHub] ERROR: %s\n' "$*" >&2
  exit 1
}

log() {
  printf '[TokenHub] %s\n' "$*"
}

require_installed() {
  [[ -f "$env_file" ]] || die "installation environment is missing: $env_file"
  [[ -f "$compose_file" ]] || die "compose file is missing: $compose_file"
}

load_environment() {
  env_file="$install_root/.env"
  compose_file="$install_root/app/docker-compose.yml"
  require_installed
  set -a
  # The file is generated by install.sh with hexadecimal values and fixed paths.
  # shellcheck disable=SC1090
  source "$env_file"
  set +a
  install_root="$TOKENHUB_INSTALL_ROOT"
  compose_file="$install_root/app/docker-compose.yml"
}

detect_compose() {
  if docker compose version >/dev/null 2>&1; then
    compose_command=(docker compose)
  elif command -v docker-compose >/dev/null 2>&1; then
    compose_command=(docker-compose)
  else
    die "Docker Compose is not installed"
  fi
}

compose() {
  "${compose_command[@]}" --env-file "$env_file" -f "$compose_file" "$@"
}

random_hex() {
  local bytes="$1"
  od -An -N "$bytes" -tx1 /dev/urandom | tr -d ' \n'
}

wait_for_health() {
  local container="$1" timeout_seconds="${2:-180}" deadline status
  deadline=$((SECONDS + timeout_seconds))
  while (( SECONDS < deadline )); do
    status="$(docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$container" 2>/dev/null || true)"
    [[ "$status" == healthy ]] && return 0
    [[ "$status" == unhealthy || "$status" == exited || "$status" == dead ]] && return 1
    sleep 2
  done
  return 1
}
